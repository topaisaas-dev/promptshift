const PENDING_CHECKOUT_STORAGE_KEY = 'promptshift_pending_checkout_state';

async function generateBundleZipBase64(
  project: CanonicalProject,
  primaryTarget: 'claude' | 'cursor' | 'openai' | 'gemini',
  includeAllFourEcosystems: boolean
): Promise<{ primaryResult: TranspileResult; b64: string }> {
  const primaryResult = UniversalTranspiler.transpile(project, primaryTarget);
  const zip = new JSZip();

  // Root files for immediate drop-in to the user's primary chosen target
  Object.entries(primaryResult.files).forEach(([filename, content]) => {
    zip.file(filename, content);
  });

  if (includeAllFourEcosystems) {
    const allTargets: ('claude' | 'cursor' | 'openai' | 'gemini')[] = [
      'claude',
      'cursor',
      'openai',
      'gemini',
    ];
    for (const tgt of allTargets) {
      const res = tgt === primaryTarget ? primaryResult : UniversalTranspiler.transpile(project, tgt);
      Object.entries(res.files).forEach(([filename, content]) => {
        zip.file(`universal-4-in-1-suite/${tgt}/${filename}`, content);
      });
    }
  }

  const auditReport = `# PromptShift Certified AST Migration Report
- Project: ${primaryResult.projectName}
- Primary Target: ${primaryResult.targetPlatform.toUpperCase()}
- Bundle Mode: ${includeAllFourEcosystems ? 'Universal 4-in-1 Suite (Cursor + Claude + OpenAI + Gemini)' : 'Free Starter Single-Target Export'}
- Certified AST Parity Score: ${primaryResult.parityScore}%
- Exposed Secrets Redacted In-RAM: ${primaryResult.alerts.length}
- Privacy Architecture: 100% Ephemeral In-RAM (Zero Server Retention)
- Generated by: https://promptshift.dev
`;
  zip.file('MIGRATION_AUDIT_REPORT.md', auditReport);

  const b64 = await zip.generateAsync({ type: 'base64' });
  return { primaryResult, b64 };
}

